-- Catálogo de modelos de caixa (compartilhado entre filiais).
CREATE TABLE IF NOT EXISTS caixa_modelos (
  id                      SERIAL PRIMARY KEY,
  nome                    TEXT NOT NULL UNIQUE,
  medida_mm               TEXT,
  lead_time_dias          INTEGER,
  estoque_seguranca_pct   NUMERIC(5,2) NOT NULL DEFAULT 0.20,
  ativo                   BOOLEAN NOT NULL DEFAULT TRUE,
  created_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Mapeamento produto (SKU) -> modelo de caixa usado pra embalar.
-- modelo_id fica NULL para os SKUs ainda sem embalagem padrão definida.
CREATE TABLE IF NOT EXISTS produto_caixa (
  sku         TEXT PRIMARY KEY,
  produto     TEXT NOT NULL,
  modelo_id   INTEGER REFERENCES caixa_modelos(id),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Entradas (compra) e saídas (uso) de caixa, por filial.
-- Escopo inicial: só filial = 'SP'. A coluna já existe pra expandir
-- para SUL e TRADE depois sem precisar de migração nova.
CREATE TABLE IF NOT EXISTS caixa_movimentacoes (
  id            SERIAL PRIMARY KEY,
  modelo_id     INTEGER NOT NULL REFERENCES caixa_modelos(id),
  filial        TEXT NOT NULL,
  tipo          TEXT NOT NULL CHECK (tipo IN ('entrada','saida')),
  quantidade    INTEGER NOT NULL CHECK (quantidade > 0),
  data          DATE NOT NULL,
  observacao    TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_caixa_mov_modelo_filial_data ON caixa_movimentacoes (modelo_id, filial, data);
CREATE INDEX IF NOT EXISTS idx_produto_caixa_modelo ON produto_caixa (modelo_id);

